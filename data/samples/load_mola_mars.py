import pandas as pd
import numpy as np

# ── Load sample CSV ────────────────────────────────────────────────────────
df = pd.read_csv(r"F:\Sem5\nasa\abid\data\samples\mola_mars_jezero_sample.csv")
print(df.head())
print(f"\nShape: {df.shape}")
print(f"\nStatistics:\n{df['elevation_m'].describe()}")

# ── Filter out nodata ──────────────────────────────────────────────────────
valid = df.dropna(subset=['elevation_m'])
print(f"\nValid pixels: {len(valid)} / {len(df)}")

# ── Basic regional query: find highest elevation pixels ───────────────────
if 'elevation_m' in df.columns:
    top10 = valid.nlargest(10, 'elevation_m')
    print("\nTop 10 highest elevation_m (meters):")
    print(top10[['latitude', 'longitude', 'elevation_m']].to_string(index=False))
